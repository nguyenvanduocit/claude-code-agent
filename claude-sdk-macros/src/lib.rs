/// #[claude_tool] — derive a `ToolDef` from an async fn at compile time.
///
/// Usage:
/// ```rust,ignore
/// /// Search the filesystem for files matching a pattern
/// #[claude_tool]
/// async fn search_files(pattern: String, max_results: u64) -> anyhow::Result<Vec<String>> {
///     // implementation
/// }
/// ```
///
/// Generates an additional function:
/// ```rust,ignore
/// fn search_files_tool_def() -> claude_sdk::protocol::ToolDef { ... }
/// ```
///
/// Type mapping:
///   String / &str    → {"type":"string"}
///   i8..i128/u8..u128/f32/f64/usize/isize → {"type":"number"}
///   bool             → {"type":"boolean"}
///   Vec<String>      → {"type":"array","items":{"type":"string"}}
///   Vec<_>           → {"type":"array"}
///   Option<T>        → same as T but NOT added to `required`
///   anything else    → {"type":"object"}
use proc_macro::TokenStream;
use proc_macro2::TokenStream as TokenStream2;
use quote::{format_ident, quote};
use syn::{
    parse_macro_input, Attribute, FnArg, GenericArgument, ItemFn, Lit, Meta, Pat, PathArguments,
    ReturnType, Type,
};

#[proc_macro_attribute]
pub fn claude_tool(_attr: TokenStream, item: TokenStream) -> TokenStream {
    let input = parse_macro_input!(item as ItemFn);
    let expanded = impl_claude_tool(input);
    TokenStream::from(expanded)
}

fn impl_claude_tool(func: ItemFn) -> TokenStream2 {
    let fn_name = &func.sig.ident;
    let def_fn_name = format_ident!("{}_tool_def", fn_name);
    let name_str = fn_name.to_string();

    // Extract doc comment from attributes.
    let description = extract_doc(&func.attrs);

    // Build properties and required lists.
    let mut prop_entries: Vec<TokenStream2> = vec![];
    let mut required_entries: Vec<String> = vec![];

    for input in &func.sig.inputs {
        if let FnArg::Typed(pat_type) = input {
            // Extract param name.
            let param_name = match pat_type.pat.as_ref() {
                Pat::Ident(p) => p.ident.to_string(),
                _ => continue,
            };

            let (is_optional, schema) = type_to_schema(&pat_type.ty);

            let name_lit = &param_name;
            prop_entries.push(quote! {
                #name_lit: #schema
            });

            if !is_optional {
                required_entries.push(param_name);
            }
        }
    }

    let required_tokens: Vec<TokenStream2> = required_entries
        .iter()
        .map(|s| quote! { #s })
        .collect();

    let schema_ts = if prop_entries.is_empty() {
        quote! {
            Some(serde_json::json!({
                "type": "object",
                "properties": {}
            }))
        }
    } else {
        quote! {
            Some(serde_json::json!({
                "type": "object",
                "properties": {
                    #(#prop_entries),*
                },
                "required": [#(#required_tokens),*]
            }))
        }
    };

    quote! {
        #func

        /// Auto-generated by `#[claude_tool]` — returns the ToolDef for this function.
        pub fn #def_fn_name() -> claude_sdk::protocol::ToolDef {
            claude_sdk::protocol::ToolDef {
                name: #name_str.into(),
                description: #description.into(),
                input_schema: #schema_ts,
            }
        }
    }
}

/// Extract the concatenated doc comment from `///` attributes.
fn extract_doc(attrs: &[Attribute]) -> String {
    let mut lines = vec![];
    for attr in attrs {
        if attr.path().is_ident("doc") {
            if let Meta::NameValue(nv) = &attr.meta {
                if let syn::Expr::Lit(el) = &nv.value {
                    if let Lit::Str(s) = &el.lit {
                        lines.push(s.value().trim().to_string());
                    }
                }
            }
        }
    }
    lines.join(" ")
}

/// Returns (is_optional, json_schema_tokens).
fn type_to_schema(ty: &Type) -> (bool, TokenStream2) {
    match ty {
        Type::Path(tp) => {
            let segs = &tp.path.segments;
            if segs.is_empty() {
                return (false, quote! { {"type": "object"} });
            }
            let last = segs.last().unwrap();
            let name = last.ident.to_string();

            // Option<T> → unwrap inner, mark optional
            if name == "Option" {
                if let PathArguments::AngleBracketed(ab) = &last.arguments {
                    if let Some(GenericArgument::Type(inner)) = ab.args.first() {
                        let (_, inner_schema) = type_to_schema(inner);
                        return (true, inner_schema);
                    }
                }
                return (true, quote! { {"type": "object"} });
            }

            // Vec<T>
            if name == "Vec" {
                if let PathArguments::AngleBracketed(ab) = &last.arguments {
                    if let Some(GenericArgument::Type(inner)) = ab.args.first() {
                        if let Type::Path(itp) = inner {
                            if let Some(iseg) = itp.path.segments.last() {
                                if iseg.ident == "String" || iseg.ident == "str" {
                                    return (false, quote! { {"type": "array", "items": {"type": "string"}} });
                                }
                            }
                        }
                    }
                }
                return (false, quote! { {"type": "array"} });
            }

            let schema = match name.as_str() {
                "String" | "str" => quote! { {"type": "string"} },
                "bool" => quote! { {"type": "boolean"} },
                "i8" | "i16" | "i32" | "i64" | "i128" | "isize"
                | "u8" | "u16" | "u32" | "u64" | "u128" | "usize"
                | "f32" | "f64" => quote! { {"type": "number"} },
                _ => quote! { {"type": "object"} },
            };
            (false, schema)
        }
        Type::Reference(tr) => type_to_schema(&tr.elem),
        _ => (false, quote! { {"type": "object"} }),
    }
}
